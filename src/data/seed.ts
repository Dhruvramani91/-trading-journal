function makeSvgPhoto(
  label: string,
  direction: 'bull' | 'bear',
  color: string,
): string {
  const bars = direction === 'bull'
    ? [
        { x: 10, y: 80, h: 20, c: '#9A9AA6' },
        { x: 25, y: 70, h: 30, c: '#9A9AA6' },
        { x: 40, y: 55, h: 45, c: '#10B981' },
        { x: 55, y: 40, h: 60, c: '#10B981' },
        { x: 70, y: 25, h: 75, c: '#10B981' },
        { x: 85, y: 15, h: 85, c: '#10B981' },
      ]
    : [
        { x: 10, y: 10, h: 90, c: '#9A9AA6' },
        { x: 25, y: 20, h: 80, c: '#9A9AA6' },
        { x: 40, y: 35, h: 65, c: '#F43F5E' },
        { x: 55, y: 50, h: 50, c: '#F43F5E' },
        { x: 70, y: 65, h: 35, c: '#F43F5E' },
        { x: 85, y: 75, h: 25, c: '#F43F5E' },
      ];

  const rectsSvg = bars
    .map(
      (b) =>
        `<rect x="${b.x}" y="${100 - b.y - b.h / 2}" width="12" height="${Math.max(b.h / 2, 4)}" rx="2" fill="${b.c}" opacity="0.85"/>`,
    )
    .join('');

  const dirLabel = direction === 'bull' ? 'LONG' : 'SHORT';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="320" height="180" viewBox="0 0 320 180"><rect width="320" height="180" fill="#0E0E12"/><rect width="320" height="180" fill="none" stroke="#26262E" stroke-width="1"/><line x1="0" y1="60" x2="320" y2="60" stroke="#26262E" stroke-width="0.5"/><line x1="0" y1="90" x2="320" y2="90" stroke="#26262E" stroke-width="0.5"/><line x1="0" y1="120" x2="320" y2="120" stroke="#26262E" stroke-width="0.5"/><g transform="scale(2.8,1.5) translate(0,4)">${rectsSvg}</g><polyline points="${direction === 'bull' ? '20,150 60,130 100,110 140,85 180,60 220,42 260,28 300,18' : '20,18 60,30 100,50 140,75 180,95 220,115 260,135 300,155'}" fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/><text x="8" y="14" font-family="monospace" font-size="9" fill="#6B6B78">${label}</text><text x="268" y="14" font-family="monospace" font-size="9" fill="${color}">${dirLabel}</text></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

